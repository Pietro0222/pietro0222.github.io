#!/usr/bin/env python3
"""Move the map data embedded in holomap/index.html into separate JSON files.

The HOLOMAP page used to ship ~13 MB of data inline (`const DATA={...}` and
`const PK={...}`). This script extracts them into holomap/data/*.json and
rewrites index.html so the data is fetched at startup, in parallel with the
parsing of three.js, before the application code runs.

The application code itself is left untouched: it is kept inline in a
`<script type="text/plain" id="holomap-app">` block and executed, in the
global scope, once the data is available (window.DATA and window.PK).

Usage:
    python3 scripts/split_holomap_data.py [path/to/index.html]

It is safe to run again: a page that has already been split is left as is,
so a freshly generated monolithic index.html can be split with one command.
"""

import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_PAGE = ROOT / "holomap" / "index.html"

# DATA keys grouped by file. Every key not listed here goes to core.json.
GROUPS = {
    "cards": ["sysCards", "routeLore"],
    "views": ["sysViews", "sysOrder"],
    "eras": ["eras"],
}

APP_ID = "holomap-app"


def dump(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def find_script_start(html, pos):
    """Return the index of the `<script` tag that encloses position `pos`."""
    start = html.rfind("<script", 0, pos)
    if start < 0:
        sys.exit("error: no <script> tag before the data")
    return start


def main():
    page = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PAGE
    html = page.read_text(encoding="utf-8")

    data_at = html.find("const DATA=")
    if data_at < 0:
        print(f"{page}: no inline DATA found, nothing to do (already split?)")
        return

    decoder = json.JSONDecoder()

    # --- extract DATA -------------------------------------------------------
    data, data_end = decoder.raw_decode(html, data_at + len("const DATA="))
    if html[data_end] == ";":
        data_end += 1

    # --- extract PK (image index), declared as `const PK={...},pkC={},pkU={};`
    pk_at = html.find("const PK=", data_end)
    if pk_at < 0:
        sys.exit("error: `const PK=` not found after DATA")
    pk, pk_end = decoder.raw_decode(html, pk_at + len("const PK="))
    rest = html[pk_end:html.find("\n", pk_end)]
    if not rest.startswith(","):
        sys.exit(f"error: unexpected text after PK: {rest[:40]!r}")

    # --- split DATA into files ---------------------------------------------
    grouped = {name: {} for name in GROUPS}
    core = {}
    for key, value in data.items():
        target = next((g for g, keys in GROUPS.items() if key in keys), None)
        (grouped[target] if target else core)[key] = value

    files = {"core": core, **grouped, "images": pk}
    out_dir = page.parent / "data"
    out_dir.mkdir(exist_ok=True)
    versions = {}
    for name, obj in files.items():
        text = dump(obj)
        (out_dir / f"{name}.json").write_text(text, encoding="utf-8")
        versions[name] = hashlib.sha1(text.encode("utf-8")).hexdigest()[:10]
        print(f"  data/{name}.json  {len(text.encode('utf-8')) / 1e6:6.2f} MB")

    # --- rewrite the page ---------------------------------------------------
    app_tag_start = find_script_start(html, data_at)
    app_tag_end = html.index(">", app_tag_start) + 1
    if html[app_tag_start:app_tag_end] != "<script>":
        sys.exit(f"error: unexpected app tag {html[app_tag_start:app_tag_end]!r}")
    app_close = html.index("</script>", pk_end)

    # `const PK={...},pkC={},pkU={};` -> `const pkC={},pkU={};`
    app_body = (
        html[app_tag_end:data_at]
        + "/* map data: loaded from data/*.json (see scripts/split_holomap_data.py) */"
        + html[data_end:pk_at]
        + "const "
        + rest[1:]
        + html[pk_end + len(rest):app_close]
    )

    file_list = ",".join(f'["{n}","{v}"]' for n, v in versions.items())
    loader = (
        "<script>\n"
        "/* HOLOMAP data loader: fetches data/*.json (generated by scripts/split_holomap_data.py)\n"
        "   while the rest of the page is parsed; the app code runs once DATA and PK are ready */\n"
        "window.HOLOMAP_READY=(()=>{const F=[" + file_list + "];\n"
        "const get=([n,v])=>fetch('data/'+n+'.json?v='+v).then(r=>{if(!r.ok)throw new Error('data/'+n+'.json: HTTP '+r.status);return r.json()});\n"
        "return Promise.all(F.map(get)).then(L=>{const D={};F.forEach(([n],i)=>{if(n!=='images')Object.assign(D,L[i])});"
        "window.DATA=D;window.PK=L[F.findIndex(([n])=>n==='images')]})})();\n"
        "</script>\n"
    )
    starter = (
        "\n<script>\n"
        "/* run the app code (kept inline above as text) once the map data has been loaded */\n"
        "window.HOLOMAP_READY.then(()=>{const s=document.createElement('script');"
        f"s.textContent=document.getElementById('{APP_ID}').textContent;document.body.appendChild(s)}});\n"
        "</script>"
    )

    # The loader goes before the first library script, so the downloads start
    # while three.js (~600 KB of inline code) is being parsed.
    lib_at = html.find("<script>/* three.min.js")
    if lib_at < 0 or lib_at > app_tag_start:
        lib_at = app_tag_start

    new_html = (
        html[:lib_at]
        + loader
        + html[lib_at:app_tag_start]
        + f'<script type="text/plain" id="{APP_ID}">'
        + app_body
        + "</script>"
        + starter
        + html[app_close + len("</script>"):]
    )
    page.write_text(new_html, encoding="utf-8")
    print(f"{page}: {len(html.encode()) / 1e6:.2f} MB -> {len(new_html.encode()) / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
